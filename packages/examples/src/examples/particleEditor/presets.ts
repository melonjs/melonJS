import type { Effect } from "./fields";

export type Mode = "stream" | "burst";
export type Motion = "still" | "sway" | "circle";

export interface Preset {
	id: string;
	label: string;
	/** a built-in texture id */
	texture: string;
	mode: Mode;
	/** shown best with the 3D camera */
	camera?: "3d";
	/** how the emitter moves in the preview */
	motion?: Motion;
	/** where the emitter sits, as a share of the preview from its center */
	offset?: { x: number; y: number };
	effect: Partial<Effect>;
	/**
	 * With the 3D camera, on top of `effect`: a spawn depth and a spread out
	 * of the screen's plane, so the effect fills a volume instead of
	 * showing as a flat sheet.
	 */
	effect3d?: Partial<Effect>;
}

